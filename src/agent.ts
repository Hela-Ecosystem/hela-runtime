function planFor(task: string): PlannedStep[] {
  const lower = task.toLowerCase();
  const steps: PlannedStep[] = [];
  const url = extractUrl(task);
  const domain = extractDomain(task);
  const wantsScreenshot = hasAny(lower, /\b(screenshot|capture|snapshot|image)\b/);
  const wantsVerify = hasAny(lower, /\b(verify|assert|check|confirm|headline|contains|expected)\b/);
  const wantsOpen = hasAny(lower, /\b(open|go to|goto|visit|navigate|browse)\b/);
  const wantsSearch = hasAny(lower, /\b(search|find|look up|lookup)\b/);
  const wantsClick = hasAny(lower, /\b(click|press|submit|fill)\b/);
  const academic = hasAny(lower, /\b(papers?|academic|arxiv|scholar|publication)\b/) && !url && !wantsScreenshot && !wantsClick;
  // A URL or explicit browser vocabulary selects the browser. A bare "type"
  // or "open" does not: "open notes.md" is a file read, not navigation.
  const browser = Boolean(url || domain)
    || hasAny(lower, /\b(browser|web|website|webpage|page|url|headline|screenshot|snapshot|navigate|navigating|tab|render|scroll|browse|browsing)\b/);

  if (hasAny(lower, /\b(remember|store in memory|save to memory|knowledge graph|observation)\b/)) {
    steps.push({ intent: 'memory', tool: 'memory_edit', description: 'store the information in the project memory graph' });
    return steps;
  }

  // Academic research outranks generic web search: "papers on protein folding"
  // should use the arXiv/research tool even though it mentions the web.
  if (academic) {
    steps.push({ intent: 'academic', tool: 'academic_search', description: 'search for academic papers' });
    return steps;
  }

  const shellIntent = hasAny(lower, /\b(run|execute|shell|bash|command|npm|pnpm|yarn|test|build|compile|git|diff|status|disk|usage|df|du|process|curl|install|serve)\b/);
  const localExplore = hasAny(lower, /\b(find|locate|count|inspect|measure)\b/)
    && hasAny(lower, /\b(files?|director(?:y|ies)|source|code|repo(?:sitory)?|runtime|packages?|typescript|\.ts|\.js|\.mjs)\b/);
  if (!browser && (shellIntent || localExplore)) {
    steps.push({ intent: 'shell', tool: 'execute_command', description: 'run the shell command for this task' });
    return steps;
  }

  const write = !browser && hasAny(lower, /\b(write|create|save|make|append|edit)\b/) && (extractFilename(task) !== undefined || hasAny(lower, /\b(file|note|notes|document)\b/));
  if (write) {
    steps.push({ intent: 'write', tool: 'write_file', description: 'write the requested file' });
    return steps;
  }

  if (!browser) {
    const wantsList = hasAny(lower, /\b(list|show|enumerate|what)\b/) && hasAny(lower, /\b(file|files|folder|directory|dir)\b/);
    const wantsRead = hasAny(lower, /\b(read|cat|show|view|open|content|version)\b/) && extractFilename(task) !== undefined;
    if (wantsList) steps.push({ intent: 'list', tool: 'list_directory', description: 'list the requested directory' });
    if (wantsRead) steps.push({ intent: 'read', tool: 'read_file', description: 'read the requested file' });
    if (steps.length) return steps;
  }

  if (browser) {
    const wikipedia = hasAny(lower, /\bwikipedia\b/);
    if (url || domain) {
      steps.push({ intent: 'navigate', tool: 'browser_navigate', description: 'open the URL in the browser' });
    } else if (wantsOpen && wikipedia) {
      steps.push({ intent: 'navigate', tool: 'browser_navigate', description: 'open Wikipedia search in the browser' });
    } else if (wantsSearch && !wantsOpen) {
      steps.push({ intent: 'browser_search', tool: 'browser_search', description: 'search the web in the browser' });
    } else if (wantsOpen) {
      steps.push({ intent: 'navigate', tool: 'browser_navigate', description: 'open the target page' });
    }

    if (wantsSearch && (url || domain || wantsOpen)) {
      steps.push({ intent: 'type', tool: 'browser_type', description: wikipedia ? 'type the search query into Wikipedia' : 'type the search query into the page' });
      steps.push({ intent: 'press', tool: 'browser_press', description: 'submit the search' });
    } else if (wantsClick) {
      steps.push({ intent: 'click', tool: 'browser_click', description: 'click the requested element' });
    }

    if (wantsVerify) steps.push({ intent: 'assert', tool: 'browser_assert', description: 'verify the page headline or expected text' });
    if (wantsScreenshot) steps.push({ intent: 'screenshot', tool: 'browser_screenshot', description: 'take a screenshot' });
    if (!steps.length) steps.push({ intent: 'inspect', tool: 'browser_get_state', description: 'inspect the current page' });
    return steps;
  }

  if (hasAny(lower, /\bwikipedia\b/)) {
    steps.push({ intent: 'wikipedia', tool: 'wikipedia_search', description: 'search Wikipedia' });
  } else if (wantsSearch) {
    steps.push({ intent: 'google', tool: 'google_search', description: 'search the web' });
  }
  return steps;
}

function completed(step: PlannedStep, history: HistoryStep[]): boolean {
  return history.some((entry) => entry.ok && entry.intent === step.intent);
}

function pending(plan: PlannedStep[], history: HistoryStep[]): PlannedStep | undefined {
  return plan.find((step) => !completed(step, history));
}

/* ── argument repair ───────────────────────────────────────────────────── */

function schemaProperties(tool: AgentTool): Record<string, any> {
  return (tool.inputSchema?.properties ?? {}) as Record<string, any>;
}

function requiredFields(tool: AgentTool): string[] {
  return Array.isArray(tool.inputSchema?.required) ? tool.inputSchema.required.filter((name: unknown): name is string => typeof name === 'string') : [];
}

function pruneUnknown(tool: AgentTool, args: Record<string, unknown>): Record<string, unknown> {
  const properties = schemaProperties(tool);
  const allowed = new Set(Object.keys(properties));
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(args)) {
    if (!allowed.size || allowed.has(key)) out[key] = value;
  }
  return out;
}

function coerceType(value: unknown, type: unknown): unknown {
  if (type === 'string' && typeof value !== 'string') return value === undefined || value === null ? value : String(value);
  if (type === 'number' && typeof value !== 'number') {
    const n = Number(value);
    return Number.isFinite(n) ? n : undefined;
  }
  if (type === 'boolean' && typeof value !== 'boolean') {
    if (value === 'true') return true;
    if (value === 'false') return false;
    return undefined;
  }
  return value;
}

export function repairArgs(tool: AgentTool, generated: Record<string, unknown>, task: string, history: HistoryStep[], context: AgentContext): { args: Record<string, unknown>; repairs: string[] } {
  const args = pruneUnknown(tool, generated || {});
  const repairs: string[] = [];
  const set = (key: string, value: unknown, reason: string): void => {
    if (value === undefined) return;
    if (args[key] !== value) {
      args[key] = value;
      repairs.push(`${key}: ${reason}`);
    }
  };

  const properties = schemaProperties(tool);
  for (const [key, value] of Object.entries(args)) {
    const coerced = coerceType(value, properties[key]?.type);
    if (coerced !== value) {
      args[key] = coerced;
      repairs.push(`${key}: coerced to ${properties[key]?.type}`);
    }
  }

  const url = extractUrl(task);
  const domain = extractDomain(task);
  const file = extractFilename(task);
  const quotedPath = extractPath(task);
  const searchTerm = extractSearchTerm(task);
  const expected = extractExpectedText(task);
  const lower = task.toLowerCase();
  const byName = tool.name;

  if (byName === 'execute_command') {
    delete args.host;
    delete args.username;
    if (!hasAny(lower, /\b(ssh|remote|host)\b/)) repairs.push('host/username: local execution');
    if (typeof args.session === 'string' && !hasAny(lower, /\bsession\b/)) {
      delete args.session;
      repairs.push('session: default shell');
    }
    set('command', shellCommandFor(task, args.command), 'synthesized from task intent');
    let workingDirectory = context.cwd;
    const mentioned = mentionedDirectory(task);
    if (mentioned) {
      // Source trees are siblings of the workspace in an installation, so a
      // path like hela-runtime/src is relative to the installation root.
      const installationRoot = path.dirname(context.workspaceRoot);
      if (fs.existsSync(path.join(installationRoot, mentioned))) workingDirectory = installationRoot;
    }
    set('workingDirectory', workingDirectory, 'runtime cwd');
  } else if (byName === 'list_directory' || byName === 'get_directory_size') {
    set('path', quotedPath ?? context.workspaceRoot, 'workspace root');
    if (args.fileTypes !== undefined && (!Array.isArray(args.fileTypes) || args.fileTypes.some((value) => !['file', 'directory', 'symlink'].includes(String(value))))) {
      delete args.fileTypes;
      repairs.push('fileTypes: invalid filter removed');
    }
  } else if (byName === 'read_file') {
    set('path', resolveFilePath(file ?? quotedPath, context) ?? args.path, 'resolved file path');
    // The schema default is utf8. A small model regularly invents latin1 or
    // other encodings from unrelated words in the task.
    if (args.encoding !== undefined && !/\b(base64|binary|hex|utf16|latin1)\b/i.test(task)) {
      delete args.encoding;
      repairs.push('encoding: schema default (utf8)');
    }
    if (typeof args.offset !== 'number') delete args.offset;
    if (typeof args.limit !== 'number') delete args.limit;
  } else if (byName === 'write_file') {
    set('path', resolveFilePath(file ?? quotedPath, context, true) ?? args.path, 'resolved file path');
    const content = typeof args.content === 'string' ? args.content.trim() : '';
    const wantsDocument = /\b(summary|notes?|report|document|readme|article|write-?up)\b/i.test(task);
    const meta = /^(absolute paths?|the content|content|current directory|workspace root|chosen tool|generate|task:)/i.test(content);
    const tooThin = wantsDocument && (content.length < 24 || content.split(/\s+/).length <= 3);
    if (!content || meta || tooThin) {
      const after = task.match(/\b(?:with|containing|that says|content[:\s]+)\s+(.{3,500})$/i)?.[1]?.trim();
      const subject = after?.match(/\b(?:a )?summary of (?:the )?(.{2,120})$/i)?.[1]?.trim();
      const body = subject
        ? `# Summary: ${subject}\n\n${subject} — notes captured by the HeLa runtime agent.\n\nGenerated ${new Date().toISOString()}.\n`
        : after ?? `${task}\n\nGenerated by the HeLa runtime agent on ${new Date().toISOString()}.\n`;
      set('content', body, 'content synthesized from task');
    }
    if (args.encoding !== undefined && !/\b(base64|binary|hex|utf16|latin1)\b/i.test(task)) {
      delete args.encoding;
      repairs.push('encoding: schema default (utf8)');
    }
    if (typeof args.append === 'boolean' && args.append && /\b(create|new|overwrite)\b/i.test(task)) {
      set('append', false, 'create/overwrite requested');
    }
    if (typeof args.createDirs !== 'boolean' && typeof args.path === 'string' && args.path.includes('/')) {
      set('createDirs', true, 'parent directories');
    }
  } else if (byName === 'browser_navigate') {
    if (!url && hasAny(lower, /\bwikipedia\b/)) {
      const query = searchTerm && searchTerm.length < 80 ? searchTerm : 'HeLa';
      // If a separate type/press step follows, open the main page so the
      // search box is available; otherwise deep-link to search results.
      const willType = hasAny(lower, /\b(search|find|look up|lookup)\b/);
      set('url', willType ? 'https://en.wikipedia.org/wiki/Main_Page' : `https://en.wikipedia.org/wiki/Special:Search?search=${encodeURIComponent(query)}`, 'Wikipedia page URL');
    } else if (url) {
      set('url', url, 'extracted URL');
    } else if (domain) {
      set('url', `https://${domain}`, 'normalized domain URL');
    } else {
      set('url', args.url, 'model-supplied URL');
    }
    if (typeof args.retries !== 'number') delete args.retries;
    if (typeof args.retryDelay !== 'number') delete args.retryDelay;
  } else if (byName === 'browser_type') {
    const selector = looksLikeCssSelector(args.selector) ? String(args.selector) : (hasAny(lower, /\bwikipedia\b/) ? 'input[name="search"]' : 'input[type="search"], input[name="q"], input[name="search"], input');
    set('selector', selector, 'page search selector');
    set('text', searchTerm ?? extractQuoted(task) ?? args.text, 'extracted search text');
    if (typeof args.delay !== 'number') delete args.delay;
  } else if (byName === 'browser_press') {
    const key = typeof args.key === 'string' && ['Enter', 'Tab', 'Escape', 'ArrowDown', 'ArrowUp', 'PageDown', 'PageUp'].includes(args.key) ? args.key : 'Enter';
    set('key', key, 'search submission key');
  } else if (byName === 'browser_screenshot') {
    if (typeof args.mark_elements !== 'boolean') args.mark_elements = false;
  } else if (byName === 'browser_assert') {
    if (expected) {
      set('type', 'text', 'assert expected text');
      set('target', 'h1', 'headline selector');
      set('expected', expected, 'extracted expected text');
      delete args.condition;
    } else {
      set('type', 'js', 'assert JavaScript condition');
      set('target', 'document.querySelector("h1") && document.querySelector("h1").innerText.trim().length > 0', 'headline presence check');
      delete args.expected;
      delete args.condition;
    }
  } else if (byName === 'browser_search' || byName === 'google_search' || byName === 'wikipedia_search' || byName === 'academic_search') {
    const query = searchTerm ?? args.query;
    if (byName === 'wikipedia_search') {
      set('query', query, 'extracted search query');
      delete args.queries;
      delete args.coord;
      if (typeof args.limit !== 'number') delete args.limit;
      if (typeof args.radius !== 'number') delete args.radius;
      if (typeof args.lang !== 'string') delete args.lang;
    } else {
      set('query', query, 'extracted search query');
    }
  } else if (byName === 'find_files') {
    set('pattern', file ? `*${path.extname(file)}` : '*', 'file pattern');
  } else if (byName === 'memory_edit') {
    const actions = ['create_entities', 'create_relations', 'add_observations', 'delete_entities', 'delete_observations', 'delete_relations'];
    const action = actions.includes(String(args.action)) ? String(args.action) : 'add_observations';
    const entityName = typeof args.entityName === 'string' && args.entityName.trim()
      ? args.entityName.trim()
      : process.env.HELA_MEMORY_ENTITY || 'project:hela-dev-workspace-runtime';
    const note = String(args.observation ?? args.content ?? task).replace(/^remember(?:\s+that)?\s+/i, '').trim() || task;
    if (action === 'add_observations' && !Array.isArray(args.observations)) {
      set('action', action, 'memory mutation');
      set('observations', [{ entityName, contents: [note] }], 'synthesized memory observation');
      delete args.entities;
      delete args.entityName;
      delete args.observation;
      delete args.content;
    } else if (action === 'create_entities' && !Array.isArray(args.entities)) {
      set('action', action, 'memory mutation');
      set('entities', [{ name: entityName, entityType: 'project', observations: [note] }], 'synthesized memory entity');
    }
  }

  return { args, repairs };
}

export function validateArgs(tool: AgentTool, args: Record<string, unknown>): { ok: true } | { ok: false; error: string } {
  for (const key of requiredFields(tool)) {
    const value = args[key];
    if (value === undefined || value === null || (typeof value === 'string' && !value.trim())) {
      return { ok: false, error: `missing required argument '${key}'` };
    }
    const type = schemaProperties(tool)[key]?.type;
    if (type === 'array' && !Array.isArray(value)) return { ok: false, error: `'${key}' must be an array` };
    if (type === 'object' && (!value || typeof value !== 'object' || Array.isArray(value))) return { ok: false, error: `'${key}' must be an object` };
    if ((type === 'number' || type === 'integer') && typeof value !== 'number') return { ok: false, error: `'${key}' must be a number` };
    if (type === 'boolean' && typeof value !== 'boolean') return { ok: false, error: `'${key}' must be a boolean` };
  }
  return { ok: true };
}

/* ── engine adapter ────────────────────────────────────────────────────── */

function resolveSystemPath(root: string, profile: string | null): string | undefined {
  if (process.env.NEEDLE_SYSTEM_PATH && fs.existsSync(process.env.NEEDLE_SYSTEM_PATH)) return process.env.NEEDLE_SYSTEM_PATH;
  const dir = path.join(root, 'chaining-mcp', 'assets', 'needle');
  // Reach for hela-system.txt first. Several profile files contain "NOT
  // active" roster notes, and Needle's validator treats that phrasing as
  // negation and suppresses otherwise valid calls.
  const base = path.join(dir, 'hela-system.txt');
  if (fs.existsSync(base)) return base;
  if (profile) {
    const profilePath = path.join(dir, 'profiles', `${profile}.txt`);
    if (fs.existsSync(profilePath)) return profilePath;
  }
  return undefined;
}

function plannerDescription(tool: AgentTool): string {
  return PLANNER_HINTS[tool.name] ?? tool.description ?? tool.name;
}

/**
 * Needle has an 8k context. Most cell schemas are small, but a few carry deep
 * nested design objects. Keep required fields and scalar options; the repair
 * layer supplies or drops the rest.
 */
export function compactParameters(schema: any, budget = 8000): any {
  if (!schema || typeof schema !== 'object') return { type: 'object', properties: {} };
  if (JSON.stringify(schema).length <= budget) return schema;
  const source = (schema.properties ?? {}) as Record<string, any>;
  const required = new Set<string>(Array.isArray(schema.required) ? schema.required : []);
  const properties: Record<string, any> = {};
  for (const [key, value] of Object.entries(source)) {
    const type = value?.type;
    if (required.has(key) || ['string', 'number', 'integer', 'boolean'].includes(type)) {
      properties[key] = { type, ...(value.description ? { description: value.description } : {}) };
    }
  }
  return { type: 'object', properties, required: [...required].filter((key) => key in properties) };
}

export class NativeNeedleAgent {
  private readonly enginePath: string;
  private readonly modelPath?: string;
  private readonly systemPath?: string;
  private readonly systemText?: string;
  private readonly needleTimeoutMs: number;

  constructor(private readonly host: AgentHost, private readonly options: AgentOptions) {
    const dir = path.join(options.root, 'chaining-mcp', 'assets', 'needle');
    const candidates = needleEngineCandidates();
    const configuredEngine = process.env.NEEDLE_ENGINE_PATH;
    const discoveredEngine = candidates.map((name) => path.join(dir, name)).find((candidate) => fs.existsSync(candidate));
    this.enginePath = configuredEngine || discoveredEngine || path.join(dir, candidates[0]);
    const model = process.env.NEEDLE_MODEL_PATH || path.join(dir, 'needle3.cact');
    this.modelPath = fs.existsSync(model) ? model : undefined;
    this.systemPath = resolveSystemPath(options.root, options.profile);
    if (this.systemPath) {
      try {
        const raw = fs.readFileSync(this.systemPath, 'utf8');
        // Needle's validator sets validation.negation on roster lines such as
        // "Receptor/mobile and Plastid/3D are NOT active". That suppresses
        // otherwise valid calls, so drop those lines from the prompt copy.
        const cleaned = raw
          .split('\n')
          .filter((line) => !/\bNOT active\b/i.test(line))
          .join('\n')
          .replace(/\n{3,}/g, '\n\n')
          .trim();
        this.systemText = cleaned || raw;
      } catch {
        this.systemText = undefined;
      }
    }
    this.needleTimeoutMs = options.needleTimeoutMs ?? 30000;
  }

  health(): { ok: boolean; engine: string; model?: string; system?: string; sanitized?: boolean; detail?: string } {
    if (!fs.existsSync(this.enginePath)) return { ok: false, engine: this.enginePath, detail: 'Needle engine not found' };
    if (!this.modelPath) return { ok: false, engine: this.enginePath, detail: 'Needle model not found' };
    let sanitized = false;
    if (this.systemPath && this.systemText) {
      try { sanitized = this.systemText !== fs.readFileSync(this.systemPath, 'utf8'); } catch { sanitized = true; }
    }
    return { ok: true, engine: this.enginePath, model: this.modelPath, system: this.systemPath, sanitized };
  }

  catalog(): AgentTool[] {
    return this.host.agentCatalog();
  }

  private async invoke(tools: Array<{ name: string; description: string; parameters: unknown }>, prompt: string): Promise<NeedleEnvelope> {
    if (!fs.existsSync(this.enginePath)) throw new Error(`Needle engine not found at ${this.enginePath}`);
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'hela-agent-'));
    const toolsFile = path.join(directory, 'tools.json');
    fs.writeFileSync(toolsFile, JSON.stringify(tools));
    const args: string[] = [];
    if (this.modelPath) args.push('--model', this.modelPath);
    if (this.systemText) {
      const systemFile = path.join(directory, 'system.txt');
      fs.writeFileSync(systemFile, this.systemText);
      args.push('--system', systemFile);
    }
    args.push('--tools', toolsFile, '--prompt', prompt, '--max', '256', '--forced');
    try {
      const stdout = await new Promise<string>((resolve, reject) => {
        execFile(this.enginePath, args, {
          timeout: this.needleTimeoutMs,
          maxBuffer: 8 * 1024 * 1024,
          env: { ...process.env, NEEDLE_TELEMETRY: '0', DO_NOT_TRACK: '1' },
        }, (error, out, stderr) => {
          if (error) reject(new Error(`needle exec failed: ${String(stderr || error.message).slice(0, 300)}`));
          else resolve(String(out));
        });
      });
      const line = stdout.trim().split('\n').filter(Boolean).pop();
      if (!line) throw new Error('needle returned no output');
      return JSON.parse(line) as NeedleEnvelope;
    } finally {
      try { fs.rmSync(directory, { recursive: true, force: true }); } catch { /* best effort */ }
    }
  }

  private async choose(shortlist: AgentTool[], task: string, step: PlannedStep | undefined, history: HistoryStep[]): Promise<string | undefined> {
    const declarations = shortlist.map((tool) => ({
      name: tool.name,
      description: plannerDescription(tool),
      parameters: { type: 'object', properties: {} },
    }));
    declarations.push({ name: DONE_TOOL, description: 'Call this when the task is complete and no further tool action is needed.', parameters: { type: 'object', properties: {} } });
    const historyText = history.slice(-4).map((entry) => `${entry.tool}(${JSON.stringify(entry.args)}) -> ${entry.ok ? (entry.result ?? '').slice(0, 300) : `ERROR ${entry.error ?? ''}`}`).join('\n');
    const prompt = [
      `Task: ${task}`,
      step ? `Current step: ${step.description}.` : 'Choose the next action that makes progress.',
      `Workspace root: ${this.host.agentContext().workspaceRoot}`,
      historyText ? `Recent actions:\n${historyText}` : '',
      'Choose the tool for this step. Call done when every requested action is complete.',
    ].filter(Boolean).join('\n');
    const result = await this.invoke(declarations, prompt);
    const call = result.function_calls?.[0] ?? result.suppressed_calls?.[0];
    if (call?.name === DONE_TOOL) return DONE_TOOL;
    if (call?.name && (shortlist.some((tool) => tool.name === call.name) || call.name === DONE_TOOL)) return call.name;
    return undefined;
  }

  private async arguments(tool: AgentTool, task: string, step: PlannedStep | undefined, history: HistoryStep[]): Promise<{ args: Record<string, unknown>; confidence?: number; reasoning?: string }> {
    const hint: Record<string, string> = {
      execute_command: 'Provide the bash command to run. Use df -h for disk usage, npm test for tests, git status/diff for repository state.',
      write_file: 'Provide path and content. Use an absolute path under the workspace root when possible.',
      read_file: 'Provide the file path. Use an absolute path when possible.',
      list_directory: 'Provide the directory path. Use an absolute path when possible.',
      browser_navigate: 'Provide the URL to open.',
      browser_type: 'Provide a CSS selector and the text to type.',
      browser_press: 'Provide the key to press, for example Enter.',
      browser_assert: 'Provide type=text with target and expected, or type=js with target as a JavaScript condition.',
      browser_search: 'Provide the search query.',
      academic_search: 'Provide the search query.',
      wikipedia_search: 'Provide the search query.',
    };
    const description = `${plannerDescription(tool)}${hint[tool.name] ? ` ${hint[tool.name]}` : ''}`;
    const historyText = history.slice(-4).map((entry) => `${entry.tool}(${JSON.stringify(entry.args)}) -> ${entry.ok ? (entry.result ?? '').slice(0, 400) : `ERROR ${entry.error ?? ''}`}`).join('\n');
    const prompt = [
      `Task: ${task}`,
      step ? `Current step: ${step.description}.` : '',
      `Chosen tool: ${tool.name}.`,
      `Workspace root: ${this.host.agentContext().workspaceRoot}`,
      `Current directory: ${this.host.agentContext().cwd}`,
      historyText ? `Recent actions:\n${historyText}` : '',
      'Generate the arguments for this tool call.',
    ].filter(Boolean).join('\n');
    const result = await this.invoke([{ name: tool.name, description, parameters: compactParameters(tool.inputSchema) }], prompt);
    const call = result.function_calls?.[0] ?? result.suppressed_calls?.[0];
    const args = call?.arguments && typeof call.arguments === 'object' && !Array.isArray(call.arguments) ? call.arguments as Record<string, unknown> : {};
    return { args, confidence: result.confidence, reasoning: result.reasoning };
  }

  async plan(args: Record<string, unknown>): Promise<Record<string, unknown>> {
    const task = String(args.task ?? '').trim();
    if (!task) return { ok: false, error: 'task is required' };
    const catalog = this.catalog();
    const plan = planFor(task);
    const retrieved = retrieveTools(catalog, task, [], Math.max(MAX_SHORTLIST, Number(args.limit) || MAX_SHORTLIST));
    return {
      ok: true,
      task,
      planner: 'needle3',
      catalog: { total: catalog.length },
      plan,
      retrieved: retrieved.map((tool) => ({ name: tool.name, cell: tool.cell, description: tool.description })),
      health: this.health(),
    };
  }

  async run(args: Record<string, unknown>): Promise<Record<string, unknown>> {
    const task = String(args.task ?? '').trim();
    if (!task) return { ok: false, error: 'task is required' };
    const maxIterations = clamp(args.maxIterations, 1, 20, 8);
    const maxToolCalls = clamp(args.maxToolCalls, 1, 30, 12);
    const maxExecutionMs = clamp(args.maxExecutionMs, 1000, 300000, 180000);
    const started = Date.now();
    const catalog = this.catalog();
    if (!catalog.length) return { ok: false, error: 'runtime tool catalog is empty' };
    const health = this.health();
    if (!health.ok) return { ok: false, error: health.detail, health };

    const planned = planFor(task);
    const history: HistoryStep[] = [];
    const notes: string[] = [];
    const retrievedNames = new Set<string>();
    let iterations = 0;
    let toolCalls = 0;
    let decision = 'running';

    while (iterations < maxIterations && toolCalls < maxToolCalls && Date.now() - started < maxExecutionMs) {
      iterations++;
      const step = planned.length ? pending(planned, history) : undefined;
      if (planned.length && !step) { decision = 'plan complete'; break; }

      let shortlist: AgentTool[];
      let preferred: AgentTool | undefined;
      if (step) {
        preferred = catalog.find((tool) => tool.name === step.tool);
        // Keep the shortlist inside the step's intent family. Needle was
        // choosing write_file for a navigate step when the shortlist mixed
        // families, which executed the wrong action.
        const alternatives = retrieveTools(catalog, `${task} ${step.description}`, history, MAX_SHORTLIST * 3)
          .filter((tool) => intentForTool(tool.name) === step.intent || tool.name === step.tool);
        shortlist = [preferred, ...alternatives].filter((tool): tool is AgentTool => Boolean(tool))
          .filter((tool, index, all) => all.findIndex((candidate) => candidate.name === tool.name) === index)
          .slice(0, MAX_SHORTLIST);
        if (!shortlist.length && preferred) shortlist = [preferred];
      } else {
        shortlist = retrieveTools(catalog, task, history, MAX_SHORTLIST);
      }
      if (!shortlist.length) { decision = 'no relevant tools'; break; }
      for (const tool of shortlist) retrievedNames.add(tool.name);

      let chosenName: string | undefined;
      try {
        chosenName = await this.choose(shortlist, task, step, history);
      } catch (error) {
        return { ok: false, error: error instanceof Error ? error.message : String(error), health, plan: planned, history };
      }

      if (chosenName === DONE_TOOL) {
        if (step) {
          chosenName = preferred?.name;
        } else {
          decision = 'needle reported done';
          break;
        }
      }
      let chosen = shortlist.find((tool) => tool.name === chosenName) ?? preferred ?? shortlist[0];
      if (step && preferred && chosen && chosen.name !== preferred.name) {
        // The deterministic step says exactly what must happen next. Record
        // Needle's disagreement, then execute the required step.
        notes.push(`step '${step.intent}': needle chose ${chosen.name}, executing ${preferred.name}`);
        chosen = preferred;
      }
      if (!chosen) { decision = 'no tool selected'; break; }

      let generated: { args: Record<string, unknown>; confidence?: number; reasoning?: string };
      try {
        generated = await this.arguments(chosen, task, step, history);
      } catch (error) {
        history.push({ iteration: iterations, intent: intentForTool(chosen.name), tool: chosen.name, args: {}, ok: false, error: error instanceof Error ? error.message : String(error), ms: 0 });
        continue;
      }
      const repaired = repairArgs(chosen, generated.args, task, history, this.host.agentContext());
      const validation = validateArgs(chosen, repaired.args);
      if (!validation.ok) {
        history.push({ iteration: iterations, intent: intentForTool(chosen.name), tool: chosen.name, args: repaired.args, ok: false, error: `${validation.error}; repairs=${repaired.repairs.join(', ')}`, ms: 0 });
        continue;
      }

      const callStarted = Date.now();
      try {
        const result = await this.host.executeAgentTool(chosen, repaired.args);
        const ms = Date.now() - callStarted;
        toolCalls++;
        history.push({
          iteration: iterations,
          intent: intentForTool(chosen.name),
          tool: chosen.name,
          args: repaired.args,
          ok: true,
          result: asText(result),
          ms,
        });
        if (!planned.length) {
          // Without a deterministic plan there is no completion predicate;
          // stop after the first successful action instead of repeating it
          // until the iteration cap.
          decision = `single action complete (${chosen.name})`;
          break;
        }
      } catch (error) {
        history.push({
          iteration: iterations,
          intent: intentForTool(chosen.name),
          tool: chosen.name,
          args: repaired.args,
          ok: false,
          error: error instanceof Error ? error.message : String(error),
          ms: Date.now() - callStarted,
        });
      }
    }

    if (decision === 'running') {
      decision = planned.length && !pending(planned, history)
        ? 'plan complete'
        : toolCalls ? 'iteration or time limit reached' : 'no tool executed';
    }
    return {
      ok: toolCalls > 0,
      workflowId: `native-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 6)}`,
      sessionId: `native-${Math.random().toString(36).slice(2, 10)}`,
      planner: 'needle3',
      health,
      catalog: { total: catalog.length, retrieved: [...retrievedNames] },
      plan: planned,
      notes,
      decision: { action: toolCalls > 0 ? 'executed' : 'stop', reason: decision },
      toolCalls,
      iterations,
      escalated: false,
      history,
    };
  }
}
