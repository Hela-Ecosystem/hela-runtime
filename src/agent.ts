function clamp(value: unknown, minimum: number, maximum: number, fallback: number): number {
  const n = typeof value === 'number' ? value : Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.max(minimum, Math.min(maximum, Math.floor(n)));
}

function asText(value: unknown, limit = 2400): string {
  if (value === undefined) return '';
  if (typeof value === 'string') return value.length > limit ? `${value.slice(0, limit)}…` : value;
  if (value && typeof value === 'object') {
    const record = value as Record<string, unknown>;
    if (Array.isArray(record.content)) {
      return asText(record.content.map((item) => (item as any)?.text ?? '').filter(Boolean).join('\n'), limit);
    }
    if (typeof record.result === 'string') return asText(record.result, limit);
    try { return asText(JSON.stringify(value), limit); } catch { return String(value).slice(0, limit); }
  }
  return String(value).slice(0, limit);
}

