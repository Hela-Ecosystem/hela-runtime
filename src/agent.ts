/**
 * Runtime-native Needle agent.
 *
 * The runtime owns the only complete view of the aggregated tool surface. A
 * cell (Mitosis) cannot see its siblings, and Needle 3 has an 8k context, so
 * neither a cell-local registry nor "declare all 236 tools" can work. This
 * module closes that gap in three stages:
 *
 *   1. retrieve: rank the full runtime catalog (lexical BM25 + intent rules)
 *   2. plan:     ask the bundled Needle engine to choose among a 4-tool
 *                shortlist plus a `done` sentinel
 *   3. execute:  call the selected cell tool in-process, feed the observation
 *                back, and repeat
 *
 * Arguments are generated by Needle and then deterministically repaired
 * against the real JSON Schema. The repair layer exists because a 45M model
 * is good at choosing an action but unreliable at copying paths, URLs and
 * shell commands; every repair is visible in the returned transcript.
 */

export interface AgentTool {
  /** Exposed name as listed by the runtime. */
  name: string;
  /** Cell id that owns the tool. */
  cell: string;
  /** Tool name inside the cell. */
  realName: string;
  description?: string;
  inputSchema: any;
}

