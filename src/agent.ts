function hasAny(text: string, pattern: RegExp): boolean {
  return pattern.test(text);
}

function extractUrl(text: string): string | undefined {
  const match = text.match(/https?:\/\/[^\s"'<>)\]]+/i);
  return match?.[0];
}

function extractDomain(text: string): string | undefined {
  const match = text.match(/\b((?:[a-z0-9-]+\.)+(?:com|org|net|io|dev|ai|app|gov|edu|co|uk|de|fr|jp|cn|info|me|xyz))\b/i);
  return match?.[1];
}

function extractQuoted(text: string): string | undefined {
  const match = text.match(/["'`]([^"'`]{2,160})["'`]/);
  return match?.[1]?.trim();
}

function extractFilename(text: string): string | undefined {
  const match = text.match(/(?:[\w.-]+\/)*[\w.-]+\.(?:md|markdown|txt|json|jsonl|js|mjs|cjs|ts|tsx|jsx|py|sh|bash|zsh|c|cc|cpp|h|hpp|css|scss|html|xml|yaml|yml|toml|ini|cfg|conf|csv|tsv|log|db|sqlite|pdf|png|jpg|jpeg|webp|svg)\b/i);
  if (match?.[0]) return match[0];
  const bare = text.match(/\b(README(?:\.md)?|LICENSE|CHANGELOG(?:\.md)?|Dockerfile|Makefile)\b/);
  return bare?.[1];
}

function resolveFilePath(value: string | undefined, context: AgentContext, forWrite = false): string | undefined {
  if (!value) return undefined;
  if (value.startsWith('/') || value.startsWith('~/')) return value;
  const installationRoot = path.dirname(context.workspaceRoot);
  const candidates = value.includes('/')
    ? [path.join(installationRoot, value), path.join(context.cwd, value), path.join(context.workspaceRoot, value)]
    : [path.join(context.workspaceRoot, value), path.join(context.cwd, value)];
  for (const candidate of candidates) if (fs.existsSync(candidate)) return candidate;
  // New files land next to an existing parent when the caller named a source
  // tree, otherwise in the workspace.
  if (forWrite || value.includes('/')) {
    for (const candidate of candidates) if (fs.existsSync(path.dirname(candidate))) return candidate;
  }
  return path.join(context.workspaceRoot, value);
}

function extractPath(text: string): string | undefined {
  const quoted = extractQuoted(text);
  if (quoted && (quoted.startsWith('/') || quoted.startsWith('./') || quoted.startsWith('~/'))) return quoted;
  const match = text.match(/(?:^|\s)((?:~\/|\/|\.\/)[^\s"'<>)\]]+)/);
  return match?.[1];
}

function extractSearchTerm(text: string): string | undefined {
  const quoted = extractQuoted(text);
  if (quoted) return quoted;
  // "recent papers on protein folding" -> "protein folding", not "recent
  // papers". Academic phrasing puts the topic after on/about.
  if (/\b(papers?|academic|arxiv|scholar|publication|research)\b/i.test(text)) {
    const about = text.match(/\b(?:papers?|research|articles?|work|publications?)\s+(?:on|about|into)\s+(.{2,140}?)(?:\s+(?:and|then)\b|[.,;]|$)/i);
    if (about?.[1]) return about[1].trim().replace(/\s+/g, ' ');
  }
  const patterns = [
    /(?:search|look up|lookup|find|google|wikipedia|research)\s+(?:for\s+)?(.{2,120}?)(?:\s+(?:and|then|on|in|at|with|using|for a|for an)\b|[.,;]|$)/i,
    /(?:about|regarding)\s+(.{2,120}?)(?:[.,;]|$)/i,
  ];
  for (const pattern of patterns) {
    const match = text.match(pattern);
    if (match?.[1]) {
      return match[1]
        .trim()
        .replace(/^(wikipedia|google|the web|the internet|web)\s+(?:for\s+)?/i, '')
        .replace(/\s+/g, ' ');
    }
  }
  return undefined;
}

function extractExpectedText(text: string): string | undefined {
  const quoted = extractQuoted(text);
  if (quoted) return quoted;
  const match = text.match(/(?:contains?|says?|reads?|expected?|equals?)\s+(.{2,120}?)(?:[.,;]|$)/i);
  return match?.[1]?.trim();
}

function mentionedDirectory(text: string): string | undefined {
  const match = text.match(/\b(?:under|inside|within|in)\s+([\w.-]+(?:\/[\w.-]+)+)/i);
  return match?.[1];
}

function shellCommandFor(task: string, modelCommand?: unknown): string | undefined {
  const lower = task.toLowerCase();
  const backtick = task.match(/`([^`]{2,300})`/);
  if (backtick) return backtick[1].trim();
  if (/\b(count|how many)\b.*\b(lines?|loc)\b/i.test(lower)) {
    const dir = mentionedDirectory(task) ?? '.';
    return `find ${dir} -type f \\( -name '*.ts' -o -name '*.tsx' -o -name '*.js' -o -name '*.mjs' \\) -print0 | xargs -0 wc -l | sort -n | tail -20`;
  }
  const commands: Array<{ pattern: RegExp; command: string }> = [
    { pattern: /\b(disk|df|free space|filesystem usage)\b.*\b(usage|space|large|biggest|largest|files)?\b/, command: "df -h; echo '--- largest files ---'; du -ah . 2>/dev/null | sort -rh | head -20" },
    { pattern: /\b(large|biggest|largest)\b.*\bfiles?\b/, command: "du -ah . 2>/dev/null | sort -rh | head -20" },
    { pattern: /\bnpm test\b|\brun (the )?tests?\b|\btest suite\b/, command: 'npm test' },
    { pattern: /\bgit diff\b/, command: 'git diff --stat; git diff' },
    { pattern: /\bgit status\b/, command: 'git status --short --branch' },
    { pattern: /\b(list|show)\b.*\b(files|directory|folder)\b/, command: 'ls -la' },
    { pattern: /\b(processes|ps|memory usage|free memory)\b/, command: 'ps aux --sort=-%mem | head -15; free -h' },
    { pattern: /\b(node|npm|pnpm|yarn) version\b/, command: 'node --version; npm --version' },
    { pattern: /\bpwd|current directory\b/, command: 'pwd' },
  ];
  for (const entry of commands) if (entry.pattern.test(lower)) return entry.command;
  if (typeof modelCommand === 'string') {
    const value = modelCommand.trim();
    if (value && value !== 'bash' && value !== 'sh' && !/^(check|list|run|execute|command)\b/i.test(value)) return value;
  }
  return undefined;
}

function looksLikeCssSelector(value: unknown): boolean {
  if (typeof value !== 'string' || !value.trim()) return false;
  if (/^https?:\/\//i.test(value)) return false;
  return /[#.[\]>+~:()=]|^(input|textarea|button|a|select|form|h[1-6]|body|html|div|span)\b/i.test(value);
}

